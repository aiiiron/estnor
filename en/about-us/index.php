<h2>How EstNor was built</h2>
</div>
<ol class="timeline">
<li><span class="year">2000</span>EstNor OÜ is founded on 20 October. A former fertiliser storage building in Kiili is purchased and rebuilt into our first manufacturing facility.</li>
<li><span class="year">2001</span>The very first handcrafted timber house leaves the new factory — the start of EstNor's production.</li>
<li><span class="year">2002</span>The team grows to five employees as demand for our houses increases.</li>
