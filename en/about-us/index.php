<li><span class="year">2022</span>EstNor becomes the first participating manufacturer in the Estonian KredEx pilot programme for serial renovation, supplying the largest volume of facade elements for twelve apartment buildings.</li>
<li><span class="year">Today</span>EstNor produces roughly 50 houses a year — around 10,000 m² of floor area — and manufactures prefabricated facade elements for serial renovation, both certified to ISO 9001, CE and EOTA.</li>
